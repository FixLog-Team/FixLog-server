-- =====================================================================
-- 워크스페이스 기본 접근 정책
-- ---------------------------------------------------------------------
-- 지금까지 상속 체인이 루트까지 올라가면 판정이 코드에 박힌 ALLOW로 끝났다
-- (PermissionEvaluator의 "워크스페이스 기본 = ALLOW").
-- 그래서 워크스페이스마다 "명시적으로 준 것만 열림"을 고를 방법이 없었다.
--
-- 폴더에는 이미 base_access가 있으므로(V8), 같은 개념을 트리 루트에도 둔다.
-- 이제 판정의 마지막 단계가 하드코딩이 아니라 데이터가 된다.
-- =====================================================================

-- 기본값을 ALLOW로 두는 이유:
-- 이미 운영 중인 워크스페이스를 DENY로 뒤집으면, 명시적 권한 없이 접근하던
-- 구성원이 일제히 차단된다. 기존 행은 현재 동작을 그대로 유지시킨다.
-- 새로 만들어지는 워크스페이스는 애플리케이션이 DENY를 명시해 저장한다
-- (WorkspaceEntity.baseAccess 초기값).
ALTER TABLE workspace
    ADD COLUMN base_access varchar(10) NOT NULL DEFAULT 'ALLOW';

COMMENT ON COLUMN workspace.base_access IS
    '상속 체인이 루트까지 올라갔을 때 적용할 기본 접근. ALLOW | DENY';
